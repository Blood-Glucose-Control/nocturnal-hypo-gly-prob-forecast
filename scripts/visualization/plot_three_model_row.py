# ── Data helpers ──────────────────────────────────────────────────────────────


def interpolate_quantile(
    q_forecasts: np.ndarray,
    q_levels: np.ndarray,
    q_target: float,
) -> np.ndarray:
    """Linearly interpolate a quantile not present in q_levels.

    Parameters
    ----------
    q_forecasts : (n_quantiles, fh)
    q_levels    : (n_quantiles,) sorted ascending
    q_target    : scalar within [q_levels[0], q_levels[-1]]
    """
    if q_target in q_levels:
        return q_forecasts[int(np.searchsorted(q_levels, q_target))]
    idx_hi = int(np.searchsorted(q_levels, q_target))
    idx_lo = idx_hi - 1
    frac = (q_target - q_levels[idx_lo]) / (q_levels[idx_hi] - q_levels[idx_lo])
    return q_forecasts[idx_lo] + frac * (q_forecasts[idx_hi] - q_forecasts[idx_lo])


def _load_npz(model_name: str) -> dict:
    """Load forecasts.npz for the given model name."""
    path = PROJECT_ROOT / RUN_DIRS[model_name] / "forecasts.npz"
    data = np.load(path, allow_pickle=False)
    return {
        "actuals": data["actuals"],  # (n_eps, 96)
        "q_forecasts": data["quantile_forecasts"],  # (n_eps, 9, 96)
        "q_levels": data["quantile_levels"].astype(float),  # (9,)
        "episode_ids": np.array(data["episode_ids"], dtype=str),  # (n_eps,)
    }


def _per_episode_rmse(npz: dict) -> np.ndarray:
    """RMSE of the median (q=0.5) forecast per episode, shape (n_eps,)."""
    q_levels = npz["q_levels"]
    median_idx = int(np.searchsorted(q_levels, 0.5))
    median_fc = npz["q_forecasts"][:, median_idx, :]
    return np.sqrt(np.mean((npz["actuals"] - median_fc) ** 2, axis=1))


# ── Candidate search ──────────────────────────────────────────────────────────


def find_candidates(top_n: int = SEARCH_TOP_N) -> list[dict]:
    """Search all three models for the best shared hypo episodes.

    Criteria
    --------
    * Actual BG dips below HYPO_THRESHOLD at least once in the forecast window.
    * Per-episode median RMSE is within the top P % for *all three* models.
      Auto-relaxes from P=10 in steps of 5 up to SEARCH_MAX_PERCENTILE until
      at least ``top_n`` candidates are found.

    Scoring rewards large BG range (dynamic movement) and deep hypoglycaemia.
    """
    print("Loading NPZ arrays for all three models…")
    model_names = list(RUN_DIRS.keys())
    npzs = {m: _load_npz(m) for m in model_names}

    # Verify that all models evaluated episodes in the same order
    ids_ref = npzs[model_names[0]]["episode_ids"]
    for m in model_names[1:]:
        if not np.array_equal(ids_ref, npzs[m]["episode_ids"]):
            raise ValueError(
                f"episode_ids mismatch between {model_names[0]} and {m}.\n"
                "The three NPZ files must come from evaluation runs that used "
                "identical episode orderings."
            )
    n_eps = len(ids_ref)
    print(f"  Verified: {n_eps:,} episodes aligned across all models.")

    rmses = {m: _per_episode_rmse(npzs[m]) for m in model_names}
    actuals = npzs[model_names[0]]["actuals"]  # identical across models
    has_hypo = actuals.min(axis=1) < HYPO_THRESHOLD

    # Auto-relax percentile threshold
    percentile_steps = list(range(10, SEARCH_MAX_PERCENTILE + 1, 5))
    mask = np.zeros(n_eps, dtype=bool)
    achieved_pct = SEARCH_MAX_PERCENTILE
    for pct in percentile_steps:
        in_pct = np.ones(n_eps, dtype=bool)
        for m in model_names:
            thr = float(np.percentile(rmses[m], pct))
            in_pct &= rmses[m] <= thr
        candidate_mask = has_hypo & in_pct
        if candidate_mask.sum() >= top_n:
            mask = candidate_mask
            achieved_pct = pct
            break
    else:
        # Absolute fallback: all hypo episodes, no RMSE filter
        mask = has_hypo
        achieved_pct = 100

    n_cands = int(mask.sum())
    print(
        f"  {n_cands} shared hypo episodes within P{achieved_pct} RMSE "
        f"for all models (need {top_n})."
    )
    if n_cands == 0:
        print(
            "  WARNING: no qualifying hypo episodes found.\n"
            f"  Check HYPO_THRESHOLD ({HYPO_THRESHOLD}) and "
            f"SEARCH_MAX_PERCENTILE ({SEARCH_MAX_PERCENTILE})."
        )
        return []

    # Score: BG range + extra weight on depth of hypoglycaemia
    min_bgs = actuals.min(axis=1)
    max_bgs = actuals.max(axis=1)
    score = (max_bgs - min_bgs) + 2.0 * np.maximum(0.0, HYPO_THRESHOLD - min_bgs)
    score[~mask] = -np.inf

    top_indices = np.argsort(score)[::-1][:top_n]

    # episodes.parquet rows are aligned 1-to-1 with NPZ episode_ids (same loop order)
    # so we can look up anchor by integer position (iloc[idx]).
    parquet_path = PROJECT_ROOT / RUN_DIRS[model_names[0]] / "episodes.parquet"
    ep_df = pd.read_parquet(parquet_path)
    anchors_arr = pd.to_datetime(ep_df["anchor"]).to_numpy()

    candidates: list[dict] = []
    for idx in top_indices:
        ep_id = str(ids_ref[idx])
        anchor_ts = pd.Timestamp(anchors_arr[idx])
        anchor_str = str(anchor_ts.date())
        pid = ep_id.split("::")[0]
        pct_ranks = {
            m: float(round(100.0 * float((rmses[m] < rmses[m][idx]).mean()), 1))
            for m in model_names
        }
        candidates.append(
            {
                "episode_idx": int(idx),
                "episode_id": ep_id,
                "patient_id": pid,
                "anchor": anchor_str,
                "min_bg": float(round(float(min_bgs[idx]), 2)),
                "rmse_c2": float(round(float(rmses[model_names[0]][idx]), 3)),
                "rmse_mo": float(round(float(rmses[model_names[1]][idx]), 3)),
                "rmse_tft": float(round(float(rmses[model_names[2]][idx]), 3)),
                "pct_c2": pct_ranks[model_names[0]],
                "pct_mo": pct_ranks[model_names[1]],
                "pct_tft": pct_ranks[model_names[2]],
            }
        )
    return candidates


