# ── Candidate resolver ────────────────────────────────────────────────────────


def _resolve_candidate() -> dict:
    """Return the active candidate.

    If CANDIDATES is empty, run the search, print results, and exit so the
    user can paste the entries into the CANDIDATES table.
    """
    if CANDIDATES:
        if ACTIVE_CANDIDATE >= len(CANDIDATES):
            raise IndexError(
                f"ACTIVE_CANDIDATE={ACTIVE_CANDIDATE} is out of range; "
                f"CANDIDATES has {len(CANDIDATES)} entries."
            )
        return CANDIDATES[ACTIVE_CANDIDATE]

    print(
        "CANDIDATES is empty.\n"
        "Running search — this loads three NPZ files (~18 MB total).\n"
        "Once you have the results, paste them into CANDIDATES and set "
        "ACTIVE_CANDIDATE to avoid re-running the search on every render.\n"
    )
    found = find_candidates(top_n=SEARCH_TOP_N)
    _print_candidates(found)
    if not found:
        sys.exit(1)
    return found[0]


# ── Figure builder ────────────────────────────────────────────────────────────


def build_figure(output_stem: str | None = None) -> None:
    """Build and save the three-model forecast row figure."""
    _apply_rcparams()

    stem = output_stem or OUTPUT_STEM
    model_names = list(RUN_DIRS.keys())
    n_models = len(model_names)

    candidate = _resolve_candidate()
    ep_idx = candidate["episode_idx"]
    ep_id = candidate["episode_id"]
    pid = candidate["patient_id"]
    anchor_dt = pd.Timestamp(candidate["anchor"])

    print(f"\nRendering: {ep_id}  (idx={ep_idx}, anchor={anchor_dt.date()})")
    print(
        f"  min BG = {candidate.get('min_bg', '?')} mmol/L  |  "
        f"RMSE: C2={candidate.get('rmse_c2','?')}  "
        f"Mo={candidate.get('rmse_mo','?')}  "
        f"TFT={candidate.get('rmse_tft','?')}"
    )

    print("Loading NPZ files…")
    npzs = {m: _load_npz(m) for m in model_names}

    print(f"Loading patient context data ({pid})…")
    ctx_data = load_context_data(pid, anchor_dt)

    ctx_t, fc_t = _make_time_axes()

    fig, axes = plt.subplots(
        1,
        n_models,
        figsize=(FIGURE_WIDTH_IN, FIGURE_HEIGHT_IN),
    )
    fig.subplots_adjust(
        left=SUBPLOT_LEFT,
        right=SUBPLOT_RIGHT,
        top=SUBPLOT_TOP,
        bottom=SUBPLOT_BOTTOM,
        wspace=SUBPLOT_WSPACE,
    )

    for col, (ax, model_name) in enumerate(zip(axes, model_names)):
        plot_panel(
            ax=ax,
            model_name=model_name,
            episode_idx=ep_idx,
            npz=npzs[model_name],
            ctx_data=ctx_data,
            ctx_t=ctx_t,
            fc_t=fc_t,
            is_leftmost=(col == 0),
            is_rightmost=(col == n_models - 1),
        )

    # Ensure all primary BG axes share the same y-limits
    for ax in axes:
        ax.set_ylim(YLIM_BG_MIN, YLIM_BG_MAX)

    # ── Shared figure legend ───────────────────────────────────────────────
    # Collect handles from the leftmost primary axis (canonical set)
    h_primary, l_primary = axes[0].get_legend_handles_labels()

    # IOB / COB handles (same normalised representation for every panel)
    iob_handle = mlines.Line2D(
        [],
        [],
        color=IOB_COLOR,
        lw=IOB_LW,
        ls="--",
        alpha=IOB_ALPHA,
        label="IOB",
    )
    cob_handle = mpatches.Patch(
        color=COB_COLOR,
        alpha=COB_ALPHA + 0.2,
        label="COB",
    )

    all_handles = h_primary + [iob_handle, cob_handle]
    all_labels = l_primary + ["IOB", "COB"]

    # Deduplicate preserving insertion order
    seen_labels: dict[str, object] = {}
    for h, lbl in zip(all_handles, all_labels):
        if lbl not in seen_labels and not lbl.startswith("_nolegend_"):
            seen_labels[lbl] = h

    fig.legend(
        list(seen_labels.values()),
        list(seen_labels.keys()),
        loc=LEGEND_LOC,
        bbox_to_anchor=LEGEND_BBOX,
        ncol=LEGEND_NCOL,
        fontsize=FONT_SIZE_LEGEND,
        frameon=LEGEND_FRAME,
    )

    # ── Save ──────────────────────────────────────────────────────────────
    OUTPUT_DIR.mkdir(parents=True, exist_ok=True)
    for fmt in OUTPUT_FORMATS:
        out = OUTPUT_DIR / f"{stem}.{fmt}"
        kwargs: dict = {"bbox_inches": "tight"}
        if fmt == "png":
            kwargs["dpi"] = OUTPUT_DPI
        fig.savefig(out, **kwargs)
        print(f"Saved → {out}")

    plt.close(fig)


# ── CLI ───────────────────────────────────────────────────────────────────────


def _parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(
        description=__doc__,
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    p.add_argument(
        "--find-candidates",
        action="store_true",
        help=(
            "Search for the best shared hypo episodes across all three models "
            "and print ready-to-paste entries for the CANDIDATES table."
        ),
    )
    p.add_argument(
        "--top-n",
        type=int,
        default=SEARCH_TOP_N,
        metavar="N",
        help=f"Number of candidates to print (default: {SEARCH_TOP_N}).",
    )
    p.add_argument(
        "--output",
        default=None,
        metavar="STEM",
        help=(
            f"Output filename stem without extension (default: {OUTPUT_STEM!r}). "
            "Files are written to results/figures/."
        ),
    )
    return p.parse_args()


def main() -> None:
    args = _parse_args()
    if args.find_candidates:
        cands = find_candidates(top_n=args.top_n)
        _print_candidates(cands)
        return
    build_figure(output_stem=args.output)


if __name__ == "__main__":
    main()
